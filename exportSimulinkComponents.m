function exportSimulinkComponents() %#codegen
% EXPORTSIMULINKCOMPONENTS Generates Simulink & Stateflow architectural definitions
% and MATLAB Function block wrappers for SIH26037 closed-loop 3D autonomous driving.
% %#codegen directive confirms Zero Dynamic Memory Allocation for C-Coder export.
%
% Architecture Subsystems:
%   1. Perception & Fusion Subsystem (stepPerception.m)
%   2. Behavioral Stateflow Subsystem (stepBehaviorStateflow.m)
%   3. Vectorized 3D DWA Local Planner Subsystem (stepDWAPlanner3D.m)
%   4. Kinematic 3D Vehicle Dynamics Subsystem (stepBicycleControl3D.m)

fprintf('=======================================================\n');
fprintf('  SIH26037: SIMULINK & STATEFLOW 3D ARCHITECTURE GENERATOR \n');
fprintf('=======================================================\n\n');

% 1. Perception Subsystem Wrapper Code
perceptionCode = sprintf([ ...
'function [trackStates, numTracks] = stepPerception(egoState3D, rawDetections) %%#codegen\n' ...
'%% MATLAB Function Block: Perception & Multi-Target Kalman Tracking\n' ...
'%% Inputs: egoState3D [7x1], rawDetections [10x6]\n' ...
'%% Outputs: trackStates [30x6], numTracks double\n' ...
'persistent tracker;\n' ...
'if isempty(tracker)\n' ...
'    tracker = kalmanTracker(0.05, 30);\n' ...
'end\n' ...
'tracker.predictAll();\n' ...
'numTracks = numel(tracker.tracks);\n' ...
'trackStates = zeros(30, 6);\n' ...
'for i = 1:numTracks\n' ...
'    trackStates(i,1:4) = tracker.tracks(i).state'';\n' ...
'    trackStates(i,5)   = tracker.tracks(i).Z;\n' ...
'    trackStates(i,6)   = tracker.tracks(i).Z_vel;\n' ...
'end\n' ...
'end\n' ...
]);

% 2. Stateflow Chart Behavior Decision Logic Code
stateflowSpec = sprintf([ ...
'%% Stateflow Chart Architectural Specification (3D Aware):\n' ...
'%% States: CRUISE, CAUTION, PACING, AVOID, EVADE_LATERAL, EMERGENCY_STOP\n' ...
'%% State Transitions:\n' ...
'%%   - CRUISE -> CAUTION        : when minDist < 6.0m || maxRisk > 0.35 || minTTC < 4.0s\n' ...
'%%   - CAUTION -> PACING        : when ~obsApproaching && minDist in [2.0, 5.0]m && minTTC in [2.0, 5.0]s\n' ...
'%%   - CAUTION / PACING -> EVADE_LATERAL : when obsApproaching && latAvailable && (minDist < 4.0m || minTTC < 3.0s)\n' ...
'%%   - CAUTION -> AVOID         : when minDist < 3.0m || maxRisk > 0.65 || minTTC < 2.2s\n' ...
'%%   - ANY -> EMERGENCY_STOP    : ONLY when (minTTC < 1.0s && ~latAvailable) || minDist < 0.8m || maxRisk > 0.98\n' ...
'%%   - EVADE_LATERAL -> CRUISE  : when clearance completed (minDist > 5.0m && maxRisk < 0.2)\n' ...
'%%   - EMERGENCY_STOP -> EVADE_LATERAL : when latAvailable && minTTC > 1.2s\n' ...
]);

% 3. Vectorized 3D DWA Local Planner Subsystem Wrapper Code
planner3DCode = sprintf([ ...
'function [vCmd, wCmd, bestPath] = stepDWAPlanner3D(egoState3D, trackStates, numTracks, goal) %%#codegen\n' ...
'%% MATLAB Function Block: Vectorized Risk-Aware 3D DWA Local Planner\n' ...
'%% Inputs: egoState3D [7x1], trackStates [30x6], numTracks double, goal [2x1]\n' ...
'%% Outputs: vCmd double, wCmd double, bestPath [40x3]\n' ...
'[vCmd, wCmd, bestPath] = stepDWAPlanner3D(egoState3D, trackStates, numTracks, goal);\n' ...
'end\n' ...
]);

% 4. Kinematic 3D Vehicle Dynamics Subsystem Code
control3DCode = sprintf([ ...
'function nextEgoState3D = stepBicycleControl3D(egoState3D, throttleCmd, steerCmd, dt) %%#codegen\n' ...
'%% MATLAB Function Block: 3D Vehicle Dynamics & Spatial Integration\n' ...
'%% Inputs: egoState3D [7x1], throttleCmd double, steerCmd double, dt double\n' ...
'%% Outputs: nextEgoState3D [1x7]\n' ...
'nextEgoState3D = stepBicycleControl3D(egoState3D, throttleCmd, steerCmd, dt);\n' ...
'end\n' ...
]);

% Print Architecture Summary to Console
fprintf('1. Perception Subsystem Wrapper (stepPerception.m):\n%s\n', perceptionCode);
fprintf('2. Stateflow Behavioral Transitions Specification:\n%s\n', stateflowSpec);
fprintf('3. 3D Planner Subsystem Wrapper (stepDWAPlanner3D.m):\n%s\n', planner3DCode);
fprintf('4. 3D Kinematic Dynamics Subsystem (stepBicycleControl3D.m):\n%s\n', control3DCode);

% Write code to file for reference/export
fprintf('[INFO] Exporting 3D Simulink block architectural guide to exportSimulinkArchitecture.txt...\n');
fid = fopen('exportSimulinkArchitecture.txt', 'w');
if fid > 0
    fprintf(fid, 'SIH26037 SIMULINK & STATEFLOW 3D ARCHITECTURE GUIDE\n\n');
    fprintf(fid, '%s\n%s\n%s\n%s\n', perceptionCode, stateflowSpec, planner3DCode, control3DCode);
    fclose(fid);
    fprintf('[SUCCESS] 3D Architecture file successfully saved!\n');
end

end
